"""Shared pytest configuration and helpers.

The repository keeps real-world repositories in ``samples/`` for integration
tests. The two adversarial torture repos are committed fixtures; other samples
are generated by ``scripts/fetch_samples.py``. Tests that need a sample must
call :func:`requires_sample` so the suite skips instead of failing when a
sample is missing.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from collections import defaultdict, deque
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
_ENV_SAMPLES_DIR = os.environ.get("CARTOG_SAMPLES_DIR")
SAMPLES_DIR = (
    Path(_ENV_SAMPLES_DIR).resolve() if _ENV_SAMPLES_DIR else REPO_ROOT / "samples"
)
FETCH_HINT = "python scripts/fetch_samples.py"


def pytest_configure(config: pytest.Config) -> None:
    """Register custom markers."""
    config.addinivalue_line(
        "markers",
        "samples: requires a cloned repository under samples/ "
        f"(fetch with `{FETCH_HINT}`)",
    )
    config.addinivalue_line(
        "markers",
        "adversarial: conformance test on a committed torture sample (runs with SCIP)",
    )


def requires_sample(name: str) -> None:
    """Skip the calling test when ``samples/<name>`` is not present."""
    sample_dir = SAMPLES_DIR / name
    if not sample_dir.is_dir():
        pytest.skip(
            f"samples/{name} is not cloned; run `{FETCH_HINT}` "
            f"(or `{FETCH_HINT} {name}`) to enable this test"
        )


def analyze_repo(repo_name: str, out_dir: Path) -> dict:
    """Run ``cartog analyze`` with SCIP on a sample and return graph.json."""
    sample = SAMPLES_DIR / repo_name
    if not sample.is_dir():
        pytest.skip(f"samples/{repo_name} missing; run `{FETCH_HINT}`")
    out_dir.mkdir(parents=True, exist_ok=True)
    proc = subprocess.run(
        [sys.executable, "-m", "cartog", "analyze", str(sample),
         "--out", str(out_dir)],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        timeout=600,
    )
    graph_path = out_dir / "graph.json"
    if not graph_path.is_file():
        pytest.fail(
            f"cartog analyze failed for {repo_name} (exit {proc.returncode}):\n"
            f"{(proc.stderr or proc.stdout)[-2000:]}"
        )
    return json.loads(graph_path.read_text(encoding="utf-8"))


