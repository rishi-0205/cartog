def expected(repo_name: str) -> dict:
    """Load the ground-truth expected.json for a torture repo."""
    path = REPO_ROOT / "tests" / "adversarial" / repo_name / "expected.json"
    return json.loads(path.read_text(encoding="utf-8"))


def reachable_subgraph(graph: dict, entry: str) -> tuple[dict, int, int]:
    """BFS from nodes whose name contains ``entry``.

    Returns (edge-kind Counter, hop count, reached-node count).
    Follows symbol-level edges only (calls/produces/consumes/serves/starts/uses/overrides).
    """
    out = defaultdict(list)
    for e in graph["edges"]:
        if e["kind"] in ("calls", "produces", "consumes", "serves", "starts", "uses", "overrides"):
            out[e["source"]].append(e)
    starts = [n["id"] for n in graph["nodes"] if entry in n["name"]]
    kinds = defaultdict(int)
    seen: set[str] = set()
    hops = 0
    q = deque((s, 0) for s in starts)
    while q:
        nid, depth = q.popleft()
        if nid in seen:
            continue
        seen.add(nid)
        for e in out.get(nid, []):
            kinds[e["kind"]] += 1
            hops += 1
            if e["target"] not in seen:
                q.append((e["target"], depth + 1))
    return kinds, hops, len(seen)
